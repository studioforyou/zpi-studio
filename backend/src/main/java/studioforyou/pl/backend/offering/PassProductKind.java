package studioforyou.pl.backend.offering;

/**
 * Kind of a pass product ({@code pass_product.kind}).
 */
public enum PassProductKind {

	/** A number of entries valid for a period. */
	ENTRY_PASS,
	/** One entry. */
	SINGLE_ENTRY,
	/** A package of personal training sessions. */
	PT_PACKAGE,
	/** Unlimited entries for a period. */
	TIME_PASS,
	/** A gift voucher. */
	VOUCHER

}
