package studioforyou.pl.backend.scheduling.internal;

import java.time.Instant;
import java.util.Collection;
import java.util.HashSet;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.BatchSize;
import org.hibernate.annotations.CreationTimestamp;

/**
 * One calendar event: a class, a personal training session, a workshop, a consultation or a
 * block, with the staff who run it and the rooms it uses. An event generated by a
 * recurring series keeps the series' id and its original start as the occurrence's identity.
 * Changing the assignments increments {@link #getVersion() the version}.
 */
@Entity
@Table(name = "schedule_event")
class ScheduleEvent {

	/** The reason of every block; the database has no dictionary of block reasons to choose from. */
	static final String BLOCK_REASON = "MAINTENANCE";

	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	private UUID id;

	@Enumerated(EnumType.STRING)
	@Column(updatable = false)
	private EventKind kind;

	@Column(name = "service_type_id")
	private UUID serviceTypeId;

	@Column(name = "series_id", updatable = false)
	private UUID seriesId;

	@Column(name = "series_original_start", updatable = false)
	private Instant seriesOriginalStart;

	@Column(name = "is_series_exception")
	private boolean seriesException;

	@Column(name = "training_group_id")
	private UUID trainingGroupId;

	private String title;

	@Column(name = "guest_name")
	private String guestName;

	@Column(name = "starts_at")
	private Instant startsAt;

	@Column(name = "ends_at")
	private Instant endsAt;

	private Short capacity;

	@Enumerated(EnumType.STRING)
	private EventVisibility visibility;

	@Enumerated(EnumType.STRING)
	private EventStatus status;

	@Column(name = "block_reason", updatable = false)
	private String blockReason;

	@Column(name = "created_by", updatable = false)
	private UUID createdBy;

	@CreationTimestamp
	@Column(name = "created_at", updatable = false)
	private Instant createdAt;

	@Column(name = "updated_at")
	private Instant updatedAt;

	@Version
	private int version;

	@ElementCollection
	@CollectionTable(name = "event_staff", joinColumns = @JoinColumn(name = "event_id"))
	@BatchSize(size = 100)
	private Set<EventStaffAssignment> staff = new HashSet<>();

	@ElementCollection
	@CollectionTable(name = "event_resource", joinColumns = @JoinColumn(name = "event_id"))
	@BatchSize(size = 100)
	private Set<EventResourceAssignment> resources = new HashSet<>();

	protected ScheduleEvent() {
	}

	/**
	 * A scheduled event.
	 *
	 * @param seriesId the series that generated the event, or {@code null} for a one-off event
	 */
	ScheduleEvent(EventKind kind, UUID serviceTypeId, UUID seriesId, String title, Short capacity,
			EventVisibility visibility, Instant startsAt, Instant endsAt, UUID createdBy) {
		this.kind = kind;
		this.serviceTypeId = serviceTypeId;
		this.seriesId = seriesId;
		this.seriesOriginalStart = (seriesId != null) ? startsAt : null;
		this.title = title;
		this.capacity = capacity;
		this.visibility = visibility;
		this.status = EventStatus.SCHEDULED;
		this.blockReason = (kind == EventKind.BLOCK) ? BLOCK_REASON : null;
		this.startsAt = startsAt;
		this.endsAt = endsAt;
		this.createdBy = createdBy;
		this.updatedAt = Instant.now();
	}

	/**
	 * Makes the given staff and resources the only ones assigned to the event. Rows that stay the
	 * same are kept, so their assignment time does not change.
	 *
	 * @return whether anything changed
	 */
	boolean replaceAssignments(Collection<EventStaffAssignment> newStaff,
			Collection<EventResourceAssignment> newResources) {
		Set<EventStaffAssignment> staffSet = Set.copyOf(newStaff);
		Set<EventResourceAssignment> resourceSet = Set.copyOf(newResources);
		if (this.staff.equals(staffSet) && this.resources.equals(resourceSet)) {
			return false;
		}
		this.staff.retainAll(staffSet);
		this.staff.addAll(staffSet);
		this.resources.retainAll(resourceSet);
		this.resources.addAll(resourceSet);
		this.updatedAt = Instant.now();
		return true;
	}

	/** Marks an occurrence of a series that differs from the series' rule. */
	void markSeriesException() {
		if (this.seriesId != null) {
			this.seriesException = true;
		}
	}

	UUID getId() {
		return this.id;
	}

	void setGuestName(String guestName) {
		this.guestName = guestName;
	}

	EventKind getKind() {
		return this.kind;
	}

	UUID getServiceTypeId() {
		return this.serviceTypeId;
	}

	UUID getSeriesId() {
		return this.seriesId;
	}

	String getTitle() {
		return this.title;
	}

	Instant getStartsAt() {
		return this.startsAt;
	}

	Instant getEndsAt() {
		return this.endsAt;
	}

	Short getCapacity() {
		return this.capacity;
	}

	EventStatus getStatus() {
		return this.status;
	}

	int getVersion() {
		return this.version;
	}

	Set<EventStaffAssignment> getStaff() {
		return Set.copyOf(this.staff);
	}

	Set<EventResourceAssignment> getResources() {
		return Set.copyOf(this.resources);
	}

	/**
	 * Moves the event to another time. An occurrence of a series keeps its original start as its
	 * identity.
	 *
	 * @return whether the time changed
	 */
	boolean reschedule(Instant newStart, Instant newEnd) {
		if (this.startsAt.equals(newStart) && this.endsAt.equals(newEnd)) {
			return false;
		}
		this.startsAt = newStart;
		this.endsAt = newEnd;
		this.updatedAt = Instant.now();
		return true;
	}

	/**
	 * Changes the title and the maximum number of participants.
	 *
	 * @param newCapacity the new limit, or {@code null} for no limit
	 * @return whether anything changed
	 */
	boolean changeDetails(String newTitle, Short newCapacity) {
		if (Objects.equals(this.title, newTitle) && Objects.equals(this.capacity, newCapacity)) {
			return false;
		}
		this.title = newTitle;
		this.capacity = newCapacity;
		this.updatedAt = Instant.now();
		return true;
	}

	/** Marks an occurrence that follows its series' rule again. */
	void clearSeriesException() {
		this.seriesException = false;
		this.updatedAt = Instant.now();
	}

	/** The start the series' rule gives the occurrence, or {@code null} for a one-off event. */
	Instant getSeriesOriginalStart() {
		return this.seriesOriginalStart;
	}

	boolean isSeriesException() {
		return this.seriesException;
	}

}
